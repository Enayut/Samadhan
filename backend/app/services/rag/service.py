"""RagService — orchestrates the SAMAADHAN advisory (RAG) layer.

Responsibilities:
- index the 18-document corpus from ``data/rag/RAG_CORPUS.md`` (+ local text),
- retrieve similar regulatory passages for a question / an incoming instrument,
- surface **organizational memory** (past obligations with the same pattern) with a
  deterministic advisory line, and
- answer questions with citations, either via a real Gemini call or via the
  deterministic extractive fallback.

Honesty invariant (matches the demo story): everything served here is labelled
**advisory**. Rules and human review decide compliance; this layer only retrieves
and summarises.
"""
